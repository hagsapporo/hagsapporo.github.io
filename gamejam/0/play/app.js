const languageButtons = document.querySelectorAll("[data-language]");

function setLanguage(language) {
  const selected = copy[language] ? language : "ja";
  document.documentElement.lang = selected;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[selected][key]) element.textContent = copy[selected][key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (copy[selected][key]) element.innerHTML = copy[selected][key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (copy[selected][key]) element.alt = copy[selected][key];
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === selected));
  });

  try {
    localStorage.setItem("hag-play-language", selected);
  } catch {
    // Language preference is optional when storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

